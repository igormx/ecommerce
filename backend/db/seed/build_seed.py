"""Regenerates backend/db/init/02-seed.sql and DATA_CLEANING_LOG.md from the source CSV.

Usage: python3 -I backend/db/seed/build_seed.py
"""
import csv
import re
from decimal import Decimal
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
CSV_PATH = ROOT / "LoanPro Code Challenge E-Commerce - LoanPro Code Challenge E-Commerce.csv"
SEED_PATH = ROOT / "backend/db/init/02-seed.sql"
LOG_PATH = ROOT / "DATA_CLEANING_LOG.md"

log = []  # (csv_line, sku, action, reason)


def q(v):
    if v is None:
        return "NULL"
    return "'" + v.replace("\\", "\\\\").replace("'", "''") + "'"


def clean(line, r):
    sku = r["sku"].strip()
    name = r["name"].strip()
    if not any(v.strip() for v in r.values()):
        log.append((line, "-", "Dropped", "Row is completely empty."))
        return None
    if not name:
        log.append((line, sku, "Dropped", "Product name is empty or whitespace only; name is required."))
        return None

    raw_price = r["price"].strip()
    if raw_price.lower() == "free":
        price = Decimal("0.00")
        log.append((line, sku, "Price 'free' -> 0.00", "Non-numeric price; 'free' means zero."))
    else:
        price = Decimal(raw_price.lstrip("$"))
        if raw_price.startswith("$"):
            log.append((line, sku, f"Price '{raw_price}' -> {price}", "Currency symbol stripped; column is numeric."))

    stock = int(r["stock"])
    if stock < 0:
        log.append((line, sku, f"Stock {stock} -> 0", "Negative stock is invalid; clamped to 0 (column is unsigned)."))
        stock = 0

    weight = r["weight_kg"].strip()
    if not weight:
        weight = None
        log.append((line, sku, "Weight '' -> NULL", "Weight not provided; unknown rather than 0."))
    category = r["category"].strip() or None
    if category is None:
        log.append((line, sku, "Category '' -> NULL", "Category not provided."))

    if re.search(r"<script|DROP TABLE", name, re.I):
        log.append((line, sku, "Kept as plain text", "Suspicious name (XSS/SQL injection test string). Stored escaped, "
                    "not altered; output must be HTML-escaped by the API/frontend and queries parameterized."))

    return dict(sku=sku, name=name, description=r["description"].strip() or None,
                category=category, price=price, stock=stock, weight=weight, line=line)


def main():
    with open(CSV_PATH, encoding="utf-8", newline="") as f:
        reader = csv.DictReader(f)
        products = {}
        for line, r in enumerate(reader, start=2):
            p = clean(line, r)
            if p is None:
                continue
            old = products.get(p["sku"])
            if old:
                same = {k: v for k, v in old.items() if k != "line"} == {k: v for k, v in p.items() if k != "line"}
                if same:
                    log.append((p["line"], p["sku"], f"Dropped duplicate of line {old['line']}",
                                "Identical in every field to the earlier row."))
                else:
                    diffs = [k for k in ("description", "category", "price", "stock", "weight") if old[k] != p[k]]
                    log.append((p["line"], p["sku"], f"Replaced line {old['line']} (last wins)",
                                f"Same SKU, same name ('{p['name']}') and category, so the same product; "
                                f"differing fields: {', '.join(diffs)}. Later row treated as the current version."))
            products[p["sku"]] = p

    rows = []
    for p in products.values():
        rows.append("({}, {}, {}, {}, {}, {}, {})".format(
            q(p["sku"]), q(p["name"]), q(p["description"]), q(p["category"]),
            p["price"], p["stock"], p["weight"] if p["weight"] is not None else "NULL"))
    sql = ("-- Generated by backend/db/seed/build_seed.py from the source CSV. Do not edit by hand.\n"
           "SET NAMES utf8mb4;\n\n"
           "INSERT INTO products (sku, name, description, category, price, stock, weight_kg) VALUES\n"
           + ",\n".join(rows) + ";\n")
    SEED_PATH.write_text(sql, encoding="utf-8")

    out = ["# Data cleaning log", "",
           f"Source: `{CSV_PATH.name}` ({line - 1} data rows). Loaded products: **{len(products)}**.", "",
           "Generated by `backend/db/seed/build_seed.py`. Line numbers refer to the CSV file (header is line 1).", "",
           "| CSV line | SKU | Action | Reason |", "|---|---|---|---|"]
    out += [f"| {l} | {s} | {a} | {why} |" for l, s, a, why in sorted(log, key=lambda x: x[0])]
    LOG_PATH.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"{len(products)} products, {len(log)} log entries")


if __name__ == "__main__":
    main()
